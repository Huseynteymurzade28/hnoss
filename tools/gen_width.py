#!/usr/bin/env python3
"""Generates text/width_table.odin from the Unicode data bundled with Python.

    python3 tools/gen_width.py > text/width_table.odin

Zero width: general categories Mn, Me, Cf (except U+00AD soft hyphen, which
terminals draw), plus Hangul medial/final jamo U+1160-U+11FF, which combine
with the preceding initial.
Wide: East Asian Width W or F (this includes emoji with default emoji
presentation since Unicode 9).
Everything else that is printable is 1. Controls are handled in code.
"""
import sys
import unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

def zero(cp):
    if cp == 0xAD:
        return False
    if 0x1160 <= cp <= 0x11FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")

def wide(cp):
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F") and not zero(cp)

def emit(name, rs):
    print(f"@(private, rodata)\n{name} := [{len(rs)}]Range{{")
    for lo, hi in rs:
        print(f"\t{{0x{lo:05x}, 0x{hi:05x}}},")
    print("}\n")

print("// Code generated by tools/gen_width.py from Unicode", unicodedata.unidata_version + ". DO NOT EDIT.")
print("package text\n")
emit("ZERO_WIDTH", ranges(zero))
emit("WIDE", ranges(wide))
